/**
 * 正文富文本块。长文（方法论/清单体）需要列表、表格与金句，
 * 短文仍可用 `contentParagraphs[].body` 单段纯文字，两者共存且互相兼容。
 */
/**
 * 段落内的一段文本。`link` 非空时渲染为站内锚点，
 * 用于正文自然嵌入内链（长文 SEO 权重传递 + 读者路径）。
 * 需要多条链接时把同一段拆成多个 entry 即可。
 */
export interface InsightRun {
  text: string;
  /** 站内绝对路径，如 "/problems/quote"；外链请用完整 URL */
  link?: string;
  /** 锚点是否在新标签打开（外链用 true） */
  external?: boolean;
}

export type InsightBlock =
  /** 普通段落 */
  | { type: "paragraph"; text: string }
  /** 带内链的段落：正文长文的常规写法 */
  | { type: "paragraph"; runs: InsightRun[] }
  /** 小节标题（h3），用于「第一个月 / 第二个月」这类阶段划分 */
  | { type: "subheading"; text: string }
  /** 无序列表 / 有序列表；`lead` 为每项前缀的加粗引导词，如「第 1-3 天：」；`runs` 支持项内内链 */
  | { type: "list"; ordered?: boolean; items: { text?: string; runs?: InsightRun[]; lead?: string }[] }
  /** 两列表格（部门场景、指标对照等） */
  | { type: "table"; head: [string, string]; rows: [string, string][] }
  /** 加粗金句，视觉上作为该节的结论锚点 */
  | { type: "emphasis"; text: string }
  /** 可勾选行动清单 */
  | { type: "checklist"; items: string[] }
  /**
   * 配图。`width`/`height` 为图片原始像素（必填，用于预留空间避免布局抖动）。
   * 路线图这类信息密度高的宽图建议配 `zoom: true`，窄屏可横向滚动查看细节。
   */
  | {
      type: "image";
      src: string;
      alt: string;
      width: number;
      height: number;
      caption?: string;
      /** 点击原图查看（宽图在窄屏不可读时的兜底） */
      zoom?: boolean;
    };

export interface InsightSection {
  heading?: string;
  /** 简写正文：仅一段纯文字。与 blocks 二选一，blocks 优先。 */
  body?: string;
  /** 富文本正文：列表/表格/金句。 */
  blocks?: InsightBlock[];
}

